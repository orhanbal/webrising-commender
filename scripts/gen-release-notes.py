#!/usr/bin/env python3
"""Check release-notes/notes.json and build the copies that ship with each app.

notes.json is the one source of the "Yenilikler" (what's new) notes:
  - Windows embeds it as it is (center-windows/Core/WecommanderCenter.Core.csproj);
  - macOS gets center-macos/Sources/CenterCore/ReleaseNotesData.swift;
  - the website gets gateway/src/release-notes.gen.ts (server-rendered page,
    sitemap, llms.txt) and gateway/ui/src/release-notes.gen.ts (React page);
    the gateway's Docker build only sees gateway/, hence the copies.

Usage:
  python3 scripts/gen-release-notes.py            write the copies
  python3 scripts/gen-release-notes.py --check    fail when notes.json is invalid or a copy is out of date
  python3 scripts/gen-release-notes.py --release-body windows|macos
      print the newest entry for that platform (Turkish and English) as
      Markdown, for a GitHub release body; prints nothing when there is none.
"""
import datetime, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "release-notes", "notes.json")
SWIFT = os.path.join(ROOT, "center-macos", "Sources", "CenterCore", "ReleaseNotesData.swift")
TS = [os.path.join(ROOT, "gateway", "src", "release-notes.gen.ts"),
      os.path.join(ROOT, "gateway", "ui", "src", "release-notes.gen.ts")]
LANGS = ["tr", "en", "de", "fr", "es", "pt-BR"]
PLATFORMS = {"windows", "macos"}
ID = re.compile(r"^\d{4}-\d{2}-\d{2}(-[a-z0-9-]+)?$")


def load():
    data = json.load(open(SOURCE, encoding="utf-8"))
    errors = []
    releases = data.get("releases") if isinstance(data, dict) else None
    if not isinstance(releases, list) or not releases:
        return None, ["notes.json needs a non-empty \"releases\" list"]
    seen, previous = set(), None
    for i, r in enumerate(releases):
        where = f"releases[{i}]"
        rid, date = r.get("id"), r.get("date")
        if not isinstance(rid, str) or not ID.match(rid):
            errors.append(f"{where}: id must look like YYYY-MM-DD or YYYY-MM-DD-name")
            continue
        where = rid
        if rid in seen:
            errors.append(f"{where}: duplicate id")
        seen.add(rid)
        try:
            datetime.date.fromisoformat(date)
        except (TypeError, ValueError):
            errors.append(f"{where}: date must be YYYY-MM-DD")
            continue
        if not rid.startswith(date):
            errors.append(f"{where}: id must start with its date")
        if previous and date > previous:
            errors.append(f"{where}: newest first, but {date} comes after {previous}")
        previous = date
        platforms = r.get("platforms", [])
        if not isinstance(platforms, list) or not set(platforms) <= PLATFORMS:
            errors.append(f"{where}: platforms must be a list of {sorted(PLATFORMS)} (empty or absent: both)")
        items = r.get("items")
        if not isinstance(items, dict):
            errors.append(f"{where}: items missing")
            continue
        extra = set(items) - set(LANGS)
        if extra:
            errors.append(f"{where}: unknown languages {sorted(extra)}")
        counts = set()
        for lang in LANGS:
            lines = items.get(lang)
            if not isinstance(lines, list) or not lines or not all(isinstance(s, str) and s.strip() for s in lines):
                errors.append(f"{where}: items.{lang} must be a non-empty list of sentences")
                continue
            counts.add(len(lines))
        if len(counts) > 1:
            errors.append(f"{where}: every language needs the same number of items")
    return releases, errors


def normalized(releases):
    return [{"id": r["id"], "date": r["date"], "platforms": list(r.get("platforms", [])),
             "items": {lang: r["items"][lang] for lang in LANGS}} for r in releases]


def swift_source(releases):
    body = json.dumps({"releases": normalized(releases)}, ensure_ascii=False, indent=1)
    assert '"###' not in body
    return ("// Generated by scripts/gen-release-notes.py from release-notes/notes.json. Do not edit.\n\n"
            "enum ReleaseNotesData {\n    static let json = ###\"\"\"\n" + body + "\n\"\"\"###\n}\n")


def ts_source(releases):
    body = json.dumps(normalized(releases), ensure_ascii=False, indent=1)
    return ("// Generated by scripts/gen-release-notes.py from release-notes/notes.json. Do not edit.\n"
            "export type ReleaseNoteLanguage = " + " | ".join(f'"{l}"' for l in LANGS) + ";\n"
            "export type ReleaseNote = { id: string; date: string; platforms: (\"windows\" | \"macos\")[]; "
            "items: Record<ReleaseNoteLanguage, string[]> };\n"
            "/** Newest first; platforms empty: both apps. */\n"
            "export const releaseNotes: ReleaseNote[] = " + body + ";\n")


def release_body(releases, platform):
    for r in releases:
        if not r.get("platforms") or platform in r["platforms"]:
            out = ["## Yenilikler", ""] + [f"- {s}" for s in r["items"]["tr"]]
            out += ["", "## What's new", ""] + [f"- {s}" for s in r["items"]["en"]]
            return "\n".join(out) + "\n"
    return ""


def main():
    releases, errors = load()
    if errors:
        for e in errors:
            print("notes.json: " + e)
        return 1
    if "--release-body" in sys.argv:
        platform = sys.argv[sys.argv.index("--release-body") + 1] if len(sys.argv) > sys.argv.index("--release-body") + 1 else ""
        if platform not in PLATFORMS:
            print("--release-body needs windows or macos", file=sys.stderr)
            return 2
        sys.stdout.write(release_body(releases, platform))
        return 0
    outputs = [(SWIFT, swift_source(releases))] + [(path, ts_source(releases)) for path in TS]
    if "--check" in sys.argv:
        stale = [p for p, text in outputs if (open(p, encoding="utf-8").read() if os.path.exists(p) else "") != text]
        if stale:
            for p in stale:
                print(f"{os.path.relpath(p, ROOT)} is out of date: run python3 scripts/gen-release-notes.py")
            return 1
        print(f"release notes up to date ({len(releases)} entries)")
        return 0
    for path, text in outputs:
        open(path, "w", encoding="utf-8").write(text)
        print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
