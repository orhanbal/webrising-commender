#!/usr/bin/env python3
"""Build center-macos/Sources/CenterCore/LStrings.swift.

Every L.t / L.f key in the macOS sources is looked up first in the macOS-only
translations (center-macos/Strings/<code>.json), then in the Windows tables
(center-windows/Core/Strings/<code>.json). A key found in neither is listed
and the script exits 1: translate it into center-macos/Strings and run again.

Usage: python3 scripts/gen-macos-strings.py [--check]
"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAC = os.path.join(ROOT, "center-macos")
OUT = os.path.join(MAC, "Sources", "CenterCore", "LStrings.swift")
CODES = ["en", "de", "pt-BR", "es", "fr"]
# Enum raw values shown through L.t(rawValue).
EXTRA = {"Onaylar", "Otonom mod", "Cihazlar", "Ayarlar"}
CALL = re.compile(r'\bL\.[tf]\(\s*"((?:[^"\\\n]|\\.)*)"')


def unescape(s):
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), s)


def keys():
    found = set(EXTRA)
    for f in glob.glob(os.path.join(MAC, "Sources", "*", "*.swift")):
        if f == OUT:
            continue
        for m in CALL.finditer(open(f, encoding="utf-8").read()):
            found.add(unescape(m.group(1)))
    return found


def main():
    ks = sorted(keys())
    missing, tables = [], {}
    for code in CODES:
        mac = json.load(open(os.path.join(MAC, "Strings", code + ".json"), encoding="utf-8"))
        win = json.load(open(os.path.join(ROOT, "center-windows", "Core", "Strings", code + ".json"), encoding="utf-8"))
        table = {}
        for k in ks:
            v = mac.get(k, win.get(k))
            if v is None:
                missing.append((code, k))
            else:
                table[k] = v
        tables[code] = table
    if missing:
        for code, k in missing:
            print(f"missing {code}: {k!r}")
        return 1
    src = ("// Generated by scripts/gen-macos-strings.py from center-macos/Strings and\n"
           "// center-windows/Core/Strings: the Turkish source text is the key. Do not edit.\n\n"
           "enum LStrings {\n    static let tables: [String: String] = [\n")
    for code in CODES:
        body = json.dumps(tables[code], ensure_ascii=False, indent=0, sort_keys=True)
        assert '"###' not in body
        src += '        "%s": ###"""\n%s\n"""###,\n' % (code, body)
    src += "    ]\n}\n"
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != src:
            print("LStrings.swift is out of date: run python3 scripts/gen-macos-strings.py")
            return 1
        print(f"LStrings.swift up to date ({len(ks)} texts)")
        return 0
    open(OUT, "w", encoding="utf-8").write(src)
    print(f"wrote {OUT} ({len(ks)} texts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
