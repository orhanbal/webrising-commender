// Regenerates src/components/iconsax/ (one module per icon, so each page chunk only
// carries the icons it uses) from the iconsax-reactjs package.
//
// iconsax-reactjs ships all six variants (Linear, Outline, Broken, Bold, Bulk, TwoTone)
// inside every icon component and picks one at runtime, so importing it directly
// bundles six drawings per icon. The UI only ever uses Linear (default) and Bold
// (selected/active), so this script renders just those two from the package and
// writes them out as static markup. The set of icons is whatever
// src/components/icons.tsx imports from "./iconsax".
//
// Usage: npm run icons
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const require = createRequire(import.meta.url);
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const iconsax = require("iconsax-reactjs");
const pkg = require("iconsax-reactjs/package.json");

const source = readFileSync(path.join(root, "src/components/icons.tsx"), "utf8");
const block = source.match(/import\s*\{([^}]*)\}\s*from\s*"\.\/iconsax"/);
if (!block) throw new Error('icons.tsx has no import from "./iconsax"');
const names = [...new Set(block[1].split(",").map(s => s.trim().split(/\s+as\s+/)[0]).filter(Boolean))].sort();

const inner = (Comp, variant) => {
  const svg = renderToStaticMarkup(React.createElement(Comp, { variant, color: "currentColor", size: 24 }));
  const body = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  if (!body) throw new Error("empty " + variant);
  return body;
};

const dir = path.join(root, "src/components/iconsax");
rmSync(dir, { recursive: true, force: true });
mkdirSync(dir);
const header = `// GENERATED by scripts/generate-icons.mjs from iconsax-reactjs@${pkg.version} (Iconsax / Vuesax icons, MIT).
// Do not edit; run \`npm run icons\`. Only the Linear and Bold variants are kept.
`;
for (const name of names) {
  const Comp = iconsax[name];
  if (!Comp) throw new Error("iconsax-reactjs has no icon named " + name);
  writeFileSync(path.join(dir, name + ".ts"), header + `import { iconsaxIcon } from "../iconsax-base";
export const ${name} = /*#__PURE__*/ iconsaxIcon(${JSON.stringify(name)},
  ${JSON.stringify(inner(Comp, "Linear"))},
  ${JSON.stringify(inner(Comp, "Bold"))});
`);
}
writeFileSync(path.join(dir, "index.ts"), header + names.map(n => `export { ${n} } from "./${n}";`).join("\n") + "\n");
